def fit(rows: list[dict], arch: "gvsoc.Arch | None" = None, verbose: bool = True):
    """Derive CostParams from calibration rows (as run_cases returns, or loaded from JSON).
    Every timed region includes one global barrier (the first `barrier` case): it is subtracted
    and becomes prm.barrier. Returns (params, report lines)."""
    import numpy as np
    from softhier_mlir.dse import cost
    arch = arch or gvsoc.Arch()
    prm = cost.CostParams()
    rep = []
    get = lambda kind: [(r["case"].p, r["cycles"]) for r in rows if r["case"].kind == kind and r["cycles"] is not None]  # noqa: E731
    bar = [c for _, c in get("barrier")]
    base = min(bar) if bar else 0
    prm.barrier = prm.group_barrier = float(base)
    rep.append(f"barrier (empty timed region): {base} cycles")
    net = lambda c: c - base  # noqa: E731

    # --- DMA load: t = fixed + row*rows + bytes/bw  (bw = link rate; fit fixed + row) ---------
    lb = cost.link_bw(arch)
    ld = [(p, net(c)) for p, c in get("load2d") if p[3] == 1]
    if ld:
        A = np.array([[1.0, p[0]] for p, _ in ld]); y = np.array([c - p[0] * p[1] * 2 / lb for p, c in ld])
        (f0, r0), *_ = np.linalg.lstsq(A, y, rcond=None)
        prm.dma_fixed, prm.dma_row = max(0.0, float(f0)), max(0.0, float(r0))
        rep.append(f"dma load: fixed {prm.dma_fixed:.0f} + {prm.dma_row:.2f}/row + bytes/{lb:.0f}  (n={len(ld)})")
    st = [(p, net(c)) for p, c in get("store") if p[3] == 1 and p[1] * 2 <= 25 * lb]   # issue-bound rows
    if st:
        A = np.array([[1.0, p[0]] for p, _ in st]); y = np.array([float(c) for _, c in st])
        (f0, r0), *_ = np.linalg.lstsq(A, y, rcond=None)
        prm.store_row = max(0.0, float(r0))
        rep.append(f"dma store: fixed {max(0.0, float(f0)):.0f} + max({prm.store_row:.2f}/row, bytes/{lb:.0f})  (n={len(st)})")
    # --- aggregate HBM rate from concurrent loads --------------------------------------------
    multi = [(p, net(c)) for p, c in get("load2d") if p[3] > 1]
    if multi:
        rates = sorted((p[3], p[3] * p[0] * p[1] * 2 / c) for p, c in multi)
        prm.hbm_agg = {1: lb, **{n: r for n, r in rates}}      # measured curve, interpolated by cost.stream_bw
        prm.hbm_bw_scale = rates[-1][1] / (lb * prm.hbm_channels)
        rep.append("aggregate HBM->TCDM: " + ", ".join(f"{n} clusters {r:.1f} B/cyc" for n, r in rates)
                   + " (not monotonic: depends on which mesh rows are active; used as a table)")
    # --- TCDM zero fill through ZOMEM ---------------------------------------------------------
    zr = [(p, net(c)) for p, c in get("zero")]
    if zr:
        big = max(zr, key=lambda t: t[0][0])
        prm.l1_zero_bw = big[0][0] / max(1.0, big[1] - prm.dma_fixed)
        rep.append("zero fill: " + ", ".join(f"{p[0]} B {c} cyc" for p, c in zr) + f" -> {prm.l1_zero_bw:.0f} B/cyc after the fixed cost")
    # --- RedMulE: grid search block cost + fixed ---------------------------------------------
    rm = [(p, net(c)) for p, c in get("redmule")]
    if rm:
        best = None
        for cb_ in np.arange(0.5, 4.01, 0.05):
            for fx in range(0, 1200, 25):
                prm.redmule_block, prm.redmule_fixed = float(cb_), float(fx)
                err = max(abs(cost.redmule_cycles(arch, prm, *p) - c) / c for p, c in rm)
                if best is None or err < best[0]:
                    best = (err, float(cb_), float(fx))
        prm.redmule_block, prm.redmule_fixed = best[1], best[2]
        rep.append(f"redmule: {prm.redmule_block:.2f} cyc/block, fixed {prm.redmule_fixed:.0f}, max err {100 * best[0]:.1f}% over {len(rm)} tiles")
        for p, c in rm:
            m = cost.redmule_cycles(arch, prm, *p)
            rep.append(f"   {p}: sim {c} model {m:.0f} ({100 * (m - c) / c:+.1f}%)  util {p[0] * p[1] * p[2] / arch.macs_per_cycle / c:.2f}")
    # --- scalar row ops: per-element cost from the single-cluster runs -------------------------
    for kind in ("layernorm", "softmax", "gelu", "add", "add_bias", "scale", "transpose"):
        one = [(p, net(c)) for p, c in get(kind) if p[2] == 0]
        if not one:
            continue
        prm.elem[kind] = 1.0
        for p, c in one:
            e = cost.rowop_est(arch, prm, kind, p[0], p[1], False)
            dma = e.cycles - e.compute
            prm.elem[kind] = max(1.0, (c - dma) / (p[0] * p[1]))
        rep.append(f"{kind}: {prm.elem[kind]:.1f} cycles/element (one cluster, {one[-1][0][0]}x{one[-1][0][1]})")
        alls = [(p, net(c)) for p, c in get(kind) if p[2] == 1]
        for p, c in alls:
            m = cost.rowop_est(arch, prm, kind, p[0], p[1], True).cycles
            rep.append(f"   {kind} {p[0]}x{p[1]} all clusters: sim {c} model {m:.0f} ({100 * (m - c) / c:+.1f}%)")
    if verbose:
        print("\n".join(rep))
    return prm, rep


def load_rows(path: str) -> list[dict]:
    return [{"case": Case(d["kind"], tuple(d["p"])), "cycles": d["cycles"], "ok": d["cycles"] is not None}
            for d in json.load(open(path))]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--home", default=os.environ.get("SOFTHIER_HOME"), help="SoftHier checkout (private copy for arch sweeps)")
    ap.add_argument("-o", "--out", help="JSON output of the raw rows")
    ap.add_argument("--cases", nargs="*", help="kind(p0,p1,..) e.g. gemm(256,768,768,256,256,256,1,1); default: calibration set")
    ap.add_argument("--fit", help="write fitted CostParams JSON here")
    ap.add_argument("--from-json", help="skip the simulation, fit from a saved rows JSON")
    a = ap.parse_args()
    if a.home:
        gvsoc.set_home(a.home)
    P = gvsoc.Arch().n_clusters
    if a.from_json:
        rows = load_rows(a.from_json)
    else:
        cases = [Case(s.split("(")[0], tuple(int(v) for v in s[s.index("(") + 1:-1].split(",") if v)) for s in a.cases] if a.cases else calibration_cases(P)
        rows = run_cases(cases)
        if not all(r["ok"] for r in rows):
            print(run_cases.last["stdout"][-2000:], file=sys.stderr)
        for r in rows:
            print(f"{str(r['case']):<40} {r['cycles']}")
        print(f"ROI {run_cases.last['roi_ns']} ns, wall {run_cases.last['wall_s']} s")
        if a.out:
            Path(a.out).write_text(json.dumps([{"kind": r["case"].kind, "p": list(r["case"].p), "cycles": r["cycles"]} for r in rows], indent=1))
    if a.fit:
        from softhier_mlir.dse import cost
        prm, _ = fit(rows)
        cost.params_to_json(prm, a.fit)


if __name__ == "__main__":
    main()
