"""Drive tests/gvsoc/ubench: time library primitives / whole kernels on GVSoC, many per run.

    cases = [Case.redmule(256, 256, 256), Case.load2d(256, 256, 768, nact=16), Case.gemm(256, 768, 768, mode="all")]
    rows = run_cases(cases)                      # [{"case": Case, "cycles": int}, ...]

The default case set (``calibration_cases``) measures what cost.py needs: RedMulE tile times
for the tile shapes the SigLIP workload uses, 2-D DMA load / per-row store rates for 1..P
concurrent clusters, barrier cost, and each row op on one and on all clusters.

    python -m softhier_mlir.dse.calibrate --home /app/softhier_dse -o calib.json
"""
from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from softhier_mlir.sim import gvsoc

HERE = Path(__file__).resolve().parents[2] / "tests" / "gvsoc" / "ubench"
KINDS = ["barrier", "redmule", "load2d", "store", "layernorm", "softmax", "gelu", "add", "add_bias", "scale", "transpose", "gemm", "summa", "zero"]
UB_RE = re.compile(r"\[ub\] (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) (\d+) cycles=(\d+)")


@dataclass(frozen=True)
class Case:
    kind: str
    p: tuple = ()

    def c_init(self) -> str:
        p = (tuple(self.p) + (0,) * 8)[:8]
        return f"{{ {KINDS.index(self.kind)}, {{ {', '.join(str(int(v)) for v in p)} }} }}"

    # ---- constructors -------------------------------------------------------------------
    @staticmethod
    def barrier() -> "Case":
        return Case("barrier")

    @staticmethod
    def redmule(tm: int, tn: int, tk: int) -> "Case":
        return Case("redmule", (tm, tn, tk))

    @staticmethod
    def load2d(rows: int, cols: int, ld: int, nact: int = 1) -> "Case":
        return Case("load2d", (rows, cols, ld, nact))

    @staticmethod
    def store(rows: int, cols: int, ld: int, nact: int = 1) -> "Case":
        return Case("store", (rows, cols, ld, nact))

    @staticmethod
    def rowop(kind: str, rows: int, cols: int, mode: str = "one") -> "Case":
        return Case(kind, (rows, cols, 1 if mode == "all" else 0))

    @staticmethod
    def gemm(M: int, N: int, K: int, tm: int = 256, tn: int = 256, tk: int = 256, pipeline: int = 1, mode: str = "all") -> "Case":
        return Case("gemm", (M, N, K, tm, tn, tk, pipeline, 1 if mode == "all" else 0))

    @staticmethod
    def summa(M: int, N: int, K: int, T: int = 256, tk: int = 256, pipeline: int = 1) -> "Case":
        return Case("summa", (M, N, K, T, tk, pipeline))

    @staticmethod
    def zero(nbytes: int) -> "Case":
        return Case("zero", (nbytes,))

    def __str__(self) -> str:
        return f"{self.kind}({','.join(str(v) for v in self.p)})"


def write_cases(cases: list[Case], path: Path = HERE / "cases.h") -> None:
    path.write_text("/* generated by softhier_mlir.dse.calibrate */\n#define UB_CASES \\\n" +
                    ", \\\n".join("    " + c.c_init() for c in cases) + "\n")


def stage_app(cases: list[Case], build_dir: Path) -> Path:
    """Copy the ubench app next to its build dir with its own cases.h, so concurrent runs
    (sweep workers, other agents) never share a source file."""
    app = build_dir.parent / (build_dir.name + "_app")
    app.mkdir(parents=True, exist_ok=True)
    shutil.copy2(HERE / "main.c", app / "main.c")
    rt = HERE.parents[2] / "runtime"
    (app / "CMakeLists.txt").write_text(
        f"set(SOURCES ${{CMAKE_CURRENT_SOURCE_DIR}}/main.c {rt}/sh_ops.c PARENT_SCOPE)\nset(INCLUDE_DIRS {rt} PARENT_SCOPE)\n")
    write_cases(cases, app / "cases.h")
    return app


def run_once(cases: list[Case], arch: gvsoc.Arch | None = None, build_dir: str | Path | None = None,
             timeout: int = 7200) -> list[dict]:
    """Build + run ONE simulation with all `cases`; one row per case (cycles = None on failure)."""
    bdir = Path(build_dir or os.environ.get("SOFTHIER_BUILD_DIR") or
                Path(tempfile.gettempdir()) / f"shbuild_{os.getpid()}").resolve()
    app = stage_app(cases, bdir)
    elf = gvsoc.build_sw(app, arch, build_dir=bdir)
    r = gvsoc.run_sim(elf, timeout=timeout)
    got = {int(m.group(1)): int(m.group(11)) for m in UB_RE.finditer(r["stdout"])}
    rows = [{"case": c, "cycles": got.get(i)} for i, c in enumerate(cases)]
    for row in rows:
        row["ok"] = row["cycles"] is not None
    run_cases.last = r
    return rows


def run_cases(cases: list[Case], arch: gvsoc.Arch | None = None, build_dir: str | Path | None = None,
              timeout: int = 7200, split_on_failure: bool = True, verbose: bool = True) -> list[dict]:
    """run_once, and when the simulation dies (some case SEQUENCES segfault the gvsoc NoC model
    although every case passes alone; a crash loses the whole buffered stdout) bisect the list
    into smaller simulations down to single cases. Failed single cases keep cycles = None."""
    rows = run_once(cases, arch, build_dir, timeout)
    bad = [i for i, r in enumerate(rows) if not r["ok"]]
    if not bad or not split_on_failure or len(cases) == 1:
        if bad and verbose:
            print(f"  [ubench] {len(bad)} case(s) failed (rc={run_cases.last['returncode']}): "
                  + ", ".join(str(cases[i]) for i in bad), file=sys.stderr)
        return rows
    if verbose:
        print(f"  [ubench] run of {len(cases)} cases died (rc={run_cases.last['returncode']}, first missing: "
              f"{cases[bad[0]]}); splitting", file=sys.stderr)
    # keep what the crashed run produced, re-run the rest in halves
    todo = bad
    mid = len(todo) // 2
    for part in (todo[:mid], todo[mid:]):
        if not part:
            continue
        sub = run_cases([cases[i] for i in part], arch, build_dir, timeout, True, verbose)
        for i, r in zip(part, sub):
            rows[i] = r
    return rows


run_cases.last = None


def calibration_cases(P: int = 16) -> list[Case]:
    cs = [Case.barrier(), Case.barrier()]
    for t in [(256, 256, 256), (128, 128, 128), (256, 256, 64), (256, 64, 256), (64, 256, 256), (256, 256, 128),
              (256, 128, 256), (128, 256, 256), (256, 256, 32), (256, 32, 256), (512, 256, 256), (256, 512, 256), (256, 256, 512)]:
        cs.append(Case.redmule(*t))
    for rows, cols in [(256, 256), (256, 64), (64, 256), (256, 128), (128, 128), (256, 32), (32, 256)]:
        cs.append(Case.load2d(rows, cols, 768, 1))
        cs.append(Case.store(rows, cols, 768, 1))
    for n in sorted({2, 3, 4, 6, 8, 12, P} - {1}):
        if n <= P:
            cs.append(Case.load2d(256, 256, 768, n))
    cs.append(Case.store(256, 256, 768, P))   # concurrent stores from a subset of clusters crash gvsoc (2026-10-08)
    cs += [Case.zero(131072), Case.zero(32768), Case.zero(131072)]
    for kind in ["layernorm", "softmax", "gelu", "add", "add_bias", "transpose"]:
        cs.append(Case.rowop(kind, 64, 256, "one"))
        cs.append(Case.rowop(kind, 256, 768, "all"))
    return cs


